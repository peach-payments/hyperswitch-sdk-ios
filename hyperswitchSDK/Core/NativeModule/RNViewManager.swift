import Foundation
import React
// CocoaPods pulls these in through the React-RCTAppDelegate and ReactAppDependencyProvider
// pods. Swift Package Manager has no equivalent: React.framework ships
// RCTReactNativeFactory.h and friends in its Headers but leaves them out of its umbrella
// header, so `import React` does not expose them and the package failed to compile. The
// ReactNativeHeaders artifact declares them as the React_RCTAppDelegate module.
#if SWIFT_PACKAGE
import React_RCTAppDelegate
import ReactAppDependencyProvider
#endif

internal class RNViewManager: NSObject {

    internal var responseHandler: RNResponseHandler?
    internal var rootView: UIView?

    internal static let sharedInstance = RNViewManager()

    // React Native 0.82 removed the legacy architecture: RCT_NEW_ARCH_ENABLED=0 is no longer
    // honoured, and RCTRootView is marked "will be removed along with the legacy architecture".
    // Constructing one against a bridgeless runtime yields a view that segfaults in
    // objc_setAssociatedObject the moment it is added as a subview.
    //
    // RCTReactNativeFactory rather than RCTRootViewFactory directly: the latter raises from
    // -[RCTRootViewFactory createJSRuntimeFactory] when RCTHost starts, because nothing has
    // supplied a JS engine. RCTReactNativeFactory wires that up (and the dependency provider
    // the codegen generates) and exposes the root view factory it owns.
    internal lazy var factoryDelegate: HyperswitchFactoryDelegate = {
        let delegate = HyperswitchFactoryDelegate()
        // Generated by codegen; supplies the third-party modules and Fabric components.
        delegate.dependencyProvider = RCTAppDependencyProvider()
        return delegate
    }()

    internal lazy var reactNativeFactory: RCTReactNativeFactory = {
        RCTReactNativeFactory(delegate: factoryDelegate)
    }()

    internal var rootViewFactory: RCTRootViewFactory { reactNativeFactory.rootViewFactory }

    /// nil under bridgeless; every call site uses optional chaining.
    internal var bridge: RCTBridge? { rootViewFactory.bridge }

    internal func viewForModule(_ moduleName: String, initialProperties: [String: Any]?) -> UIView {
        let view = rootViewFactory.view(withModuleName: moduleName, initialProperties: initialProperties)
        self.rootView = view
        return view
    }

    internal func widgetViewForModule(_ moduleName: String, initialProperties: [String: Any]?) -> UIView {
        return rootViewFactory.view(withModuleName: moduleName, initialProperties: initialProperties)
    }
}


/// RCTReactNativeFactoryDelegate inherits RCTBridgeDelegate, RCTJSRuntimeConfiguratorProtocol
/// and RCTUIConfiguratorProtocol. RCTDefaultReactNativeFactoryDelegate supplies working
/// defaults for all of them, so only the bundle location needs overriding.
internal class HyperswitchFactoryDelegate: RCTDefaultReactNativeFactoryDelegate {
    override func bundleURL() -> URL? {
        switch Helper.getInfoPlist("HyperswitchSource") {
        case "LocalHosted":
            return RCTBundleURLProvider.sharedSettings().jsBundleURL(forBundleRoot: "index")
        case "LocalBundle":
            return Bundle.main.url(forResource: "hyperswitch", withExtension: "bundle")
        default:
            #if canImport(HyperOTA)
            return OTAServices.shared.getBundleURL()
            #else
            return HyperswitchJSBundle.url()
                ?? Bundle(for: RNViewManager.self).url(forResource: "hyperswitch", withExtension: "bundle")
            #endif
        }
    }
}

/// Locates `hyperswitch.bundle`, the JavaScript the payment sheet runs.
///
/// CocoaPods and Swift Package Manager put it in different places, and neither finds the
/// other's. CocoaPods declares it in `core.resources`, so it lands next to the class and
/// `Bundle(for:)` finds it. SPM cannot ship it that way -- it takes package source from the
/// git tag, and the bundle is a build artifact that is not committed -- so it travels as a
/// binary target instead, HyperswitchJS.xcframework, which Xcode embeds under the app's
/// Frameworks directory. `Bundle(for:)` never looks there, which is why an SPM build used to
/// resolve, compile, and then sit on a sheet with no JavaScript behind it.
internal enum HyperswitchJSBundle {
    static func url() -> URL? {
        #if SWIFT_PACKAGE
        if let embedded = Bundle.main.url(
            forResource: "hyperswitch",
            withExtension: "bundle",
            subdirectory: "Frameworks/HyperswitchJS.framework"
        ) {
            return embedded
        }
        // The framework is linked, so it is loaded; ask it directly in case the app embeds
        // frameworks somewhere other than the default location.
        if let fw = Bundle(identifier: "io.peachpayments.HyperswitchJS"),
           let inside = fw.url(forResource: "hyperswitch", withExtension: "bundle") {
            return inside
        }
        #endif
        return nil
    }
}
